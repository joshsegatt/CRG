function collectEnglish(value, result) {
  if (!value || typeof value !== "object") return;
  if (typeof value.fr === "string" && typeof value.en === "string") {
    if (Object.hasOwn(result, value.fr) && result[value.fr] !== value.en) {
      throw new Error(`Conflicting regional translation: ${value.fr}`);
    }
    result[value.fr] = value.en;
    return;
  }
  for (const item of Object.values(value)) collectEnglish(item, result);
}

const translations = {};
collectEnglish(regionalPages, translations);
export const regionalEnglish = Object.freeze(translations);
